import { test, expect } from './app-test.mjs'
import { chapterAction, chapterHeading, moveChapter, openChapterList } from './editor-helpers.mjs'
import { databaseSnapshot } from './project-fixture.mjs'
import { addStoryChapter, cardPanel, closeCard, deleteCard, newCard, newStoryWork, openStoryWindow, renameStoryChapter, saveCard, storyCard, storyEntry } from './story-settings-helpers.mjs'

test.setTimeout(60_000)

const button = (page, name) => page.getByRole('button', { name, exact: true })

test('卡片模板、别名和常用字段，卡片删除需确认且可在回收站恢复 @webkit', async ({ page, context }) => {
  await page.goto('/#/writing')
  await newStoryWork(page, '海边故事')
  const story = await openStoryWindow(page)
  const panel = cardPanel(story)
  await expect(story.getByText('海边故事', { exact: true })).toBeVisible()
  await expect(story.locator('.editor-toolbar')).toHaveCount(0)
  await button(story, '从模板开始').click()
  await story.getByRole('menuitem', { name: '地点', exact: true }).click()
  await expect(panel.getByRole('combobox', { name: '分类', exact: true })).toHaveValue('location')
  await expect(panel.getByLabel('所在区域', { exact: true })).toHaveValue('北部海岸')
  await panel.getByLabel('名称', { exact: true }).fill('潮汐港')
  await panel.getByLabel('别名', { exact: true }).fill('  旧港  \nHarbor\nＨＡＲＢＯＲ\n潮汐港')
  await panel.getByLabel('给 AI 的简述', { exact: true }).fill('只有退潮时能进港。')
  await panel.getByLabel('完整设定', { exact: true }).fill('老码头不对外开放。\n东岸有一片红树林。')
  await saveCard(story)
  await expect(panel.getByLabel('别名', { exact: true })).toHaveValue('旧港\nHarbor')
  await closeCard(story)
  await button(story, '角色').click()
  await expect(storyCard(story, '潮汐港')).toHaveCount(0)
  await button(story, '地点').click()
  const search = story.getByRole('searchbox', { name: '搜索名称或别名' })
  await search.fill('ＨＡＲＢＯＲ')
  await storyCard(story, '潮汐港').click()
  await expect(panel.getByLabel('完整设定', { exact: true })).toHaveValue('老码头不对外开放。\n东岸有一片红树林。')
  await button(story, '删除卡片').click()
  const confirm = story.getByRole('dialog', { name: '将卡片移入回收站？' })
  await confirm.getByRole('button', { name: '取消', exact: true }).click()
  await expect(storyCard(story, '潮汐港')).toBeVisible()
  await deleteCard(story)
  await expect(storyCard(story, '潮汐港')).toHaveCount(0)
  const globalTrash = await context.newPage()
  await globalTrash.goto('/#/trash')
  const row = globalTrash.getByRole('listitem').filter({ hasText: '潮汐港' })
  await expect(row).toContainText('设定卡片')
  await button(story, '回收站').click()
  await expect(story.locator('.story-trash-card')).toContainText('潮汐港')
  await story.locator('.story-trash-card').getByRole('button', { name: '恢复', exact: true }).click()
  await expect(row).toHaveCount(0)
  await button(story, '地点').click()
  await expect(storyCard(story, '潮汐港')).toBeVisible()
  await story.reload()
  await storyCard(story, '潮汐港').click()
  await expect(cardPanel(story).getByLabel('给 AI 的简述', { exact: true })).toHaveValue('只有退潮时能进港。')
})

test('编辑器和设定标签页双向同步章节、卡片名称和关联，保留已删除目标', async ({ page }) => {
  await page.goto('/#/writing')
  await newStoryWork(page, '带章节的故事')
  const story = await openStoryWindow(page)
  await newCard(story, '沈绫')
  await newCard(story, '周行')
  const panel = cardPanel(story)
  await expect(storyEntry(page)).toHaveAttribute('title', '本书有 2 张设定卡片')
  await panel.getByRole('button', { name: '关联章节', exact: true }).click()
  const linked = panel.getByRole('combobox', { name: '关联章节', exact: true })
  await linked.selectOption({ label: '第 1 章 · 第一章' })
  await panel.getByRole('button', { name: '添加状态', exact: true }).click()
  const start = panel.getByRole('combobox', { name: '从章节起', exact: true })

  await addStoryChapter(page, '出海')
  await expect(start.locator('option').filter({ hasText: '第 2 章 · 出海' })).toHaveCount(1)
  await start.selectOption({ label: '第 2 章 · 出海' })
  const startId = await start.inputValue()
  await panel.getByLabel('状态', { exact: true }).fill('接任船长')
  await panel.getByRole('button', { name: '添加关系', exact: true }).click()
  const target = panel.getByRole('combobox', { name: '目标卡片', exact: true })
  await target.selectOption({ label: '沈绫 · 角色' })
  await panel.getByLabel('关系名称', { exact: true }).fill('师徒')
  await saveCard(story)
  await openChapterList(page)
  await page.getByRole('list', { name: '章节', exact: true }).getByRole('button', { name: '第一章', exact: true }).click()
  await expect(chapterHeading(page)).toHaveText('第一章')
  await expect(storyEntry(page)).toHaveAttribute('title', '本章关联 1 张卡片 · 周行')
  await panel.getByLabel('名称', { exact: true }).fill('周船长')
  await saveCard(story)
  await expect(storyEntry(page)).toHaveAttribute('title', '本章关联 1 张卡片 · 周船长')

  await moveChapter(page, '出海', 'up')
  await expect(start.locator('option:checked')).toHaveText('第 1 章 · 出海')
  await renameStoryChapter(page, '出海', '远航')
  await expect(start.locator('option:checked')).toHaveText('第 1 章 · 远航')
  await expect(start).toHaveValue(startId)
  await chapterAction(page, '远航', '删除章节')
  await page.getByRole('dialog', { name: '删除章节？', exact: true }).getByRole('button', { name: '确认删除章节', exact: true }).click()
  await expect(start.locator('option:checked')).toHaveText('章节已不可用')
  await page.locator('.undo-toast').getByRole('button', { name: '撤销', exact: true }).click()
  await expect(start.locator('option:checked')).toHaveText('第 1 章 · 远航')

  await storyCard(story, '沈绫').click()
  await deleteCard(story)
  await storyCard(story, '周船长').click()
  await expect(target.locator('option:checked')).toHaveText('卡片已不可用')
  await button(story, '回收站').click()
  await story.locator('.story-trash-card').getByRole('button', { name: '恢复', exact: true }).click()
  await button(story, '全部卡片').click()
  await storyCard(story, '周船长').click()
  await expect(target.locator('option:checked')).toHaveText('沈绫 · 角色')
  const db = await story.evaluate(databaseSnapshot)
  expect(db.storyCards.find((card) => card.name === '周船长')).toMatchObject({
    states: [{ text: '接任船长', chapterId: JSON.parse(startId)[1] }],
    relations: [{ name: '师徒', targetCardId: db.storyCards.find((card) => card.name === '沈绫').id }],
  })
})

test('两个设定标签页并发编辑时保留未保存草稿，过期版本无法覆盖', async ({ page, context }) => {
  await page.goto('/#/writing')
  await newStoryWork(page, '并发故事')
  const first = await openStoryWindow(page)
  await newCard(first, '潮汐商会', 'faction')
  const second = await context.newPage()
  await second.goto(first.url())
  await storyCard(second, '潮汐商会').click()
  await cardPanel(second).getByLabel('目标', { exact: true }).fill('未保存的目标')
  await cardPanel(first).getByLabel('目标', { exact: true }).fill('已保存的目标')
  await saveCard(first)
  await expect(cardPanel(second).getByRole('status')).toContainText('在另一个窗口更改')
  await expect(cardPanel(second).getByLabel('目标', { exact: true })).toHaveValue('未保存的目标')
  await expect(button(second, '保存卡片')).toBeDisabled()
  await button(second, '放弃修改').click()
  await storyCard(second, '潮汐商会').click()
  await expect(cardPanel(second).getByLabel('目标', { exact: true })).toHaveValue('已保存的目标')
})
