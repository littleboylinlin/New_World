test('窄屏画布可用模板、自由字段和多个自定义标签，按别名定位并恢复卡片 @webkit', async ({ page, context }) => {
  await page.goto('/#/writing')
  await newStoryWork(page, '海边故事')
  await page.setViewportSize({ width: 390, height: 740 })
  await expect(page.getByRole('button', { name: '查找／替换', exact: true })).toBeVisible()
  await expect(storyEntry(page)).toBeHidden()
  const story = await openStoryWindow(page)
  await action(story, '标签').click()
  const tags = story.locator('.story-sidebar')
  await tags.getByLabel('标签名称', { exact: true }).first().fill('群岛')
  await action(tags, '新增标签').click()
  await expect(tags.getByLabel('标签名称').nth(1)).toHaveValue('群岛')
  const named = tags.locator('form').nth(1)
  await named.getByLabel('标签名称').fill('北部群岛')
  await tags.getByLabel('标签名称', { exact: true }).first().fill('主线')
  await action(tags, '新增标签').click()
  await expect(tags.getByLabel('标签名称').nth(2)).toHaveValue('主线')
  await expect(named.getByLabel('标签名称')).toHaveValue('北部群岛')
  await named.getByLabel('颜色').fill('#2255aa')
  await action(named, '保存').click()
  await expect.poll(async () => (await boardState(story)).scene.tags.map(({ name, color }) => [name, color]))
    .toEqual([['北部群岛', '#2255aa'], ['主线', '#64748b']])
  await action(tags, '关闭编辑面板').click()
  await action(story, '新建卡片').click()
  const panel = cardPanel(story)
  await panel.getByRole('combobox', { name: '模板' }).selectOption('character')
  await expect(panel.getByLabel('字段名').first()).toHaveValue('身份')
  await panel.getByLabel('字段名').first().fill('潮汐值班表')
  await panel.getByLabel('内容', { exact: true }).first().fill('每周二、四')
  await panel.getByLabel('别名', { exact: true }).fill('Harbor\nＨＡＲＢＯＲ\n旧港人')
  await panel.getByLabel('正文', { exact: true }).fill('码头夜班。\n清晨交接。')
  await panel.getByRole('checkbox', { name: '北部群岛' }).check()
  await panel.getByRole('checkbox', { name: '主线' }).check()
  await expect(panel.getByRole('combobox', { name: '关联章节', exact: true }).locator('option:checked')).toHaveText('第 1 章 · 第一章')
  await fillNewCard(story, '潮汐港')
  await closeCard(story)
  await action(story, '卡片列表').click()
  await story.getByRole('searchbox').fill('ＨＡＲＢＯＲ')
  await story.locator('.story-result').filter({ hasText: '潮汐港' }).click()
  await expect(storyCard(story, '潮汐港')).toHaveAttribute('aria-pressed', 'true')
  await action(story.locator('.story-tools'), '删除').click()
  const confirm = story.getByRole('dialog', { name: '将卡片移入回收站？' })
  await action(confirm, '取消').click()
  await expect(storyCard(story, '潮汐港')).toBeVisible()
  await deleteCard(story, '潮汐港')
  const globalTrash = await context.newPage()
  await globalTrash.goto('/#/trash')
  const row = globalTrash.getByRole('listitem').filter({ hasText: '潮汐港' })
  await expect(row).toContainText('设定卡片')
  await action(story, '回收站').click()
  const trash = story.locator('.story-trash-row')
  await expect(trash).toContainText('潮汐港')
  await action(trash, '恢复').click()
  await expect(row).toHaveCount(0)
  await story.reload()
  const restored = (await boardState(story)).scene.nodes[0]
  expect(restored).toMatchObject({
    name: '潮汐港', aliases: ['Harbor', '旧港人'], fields: expect.arrayContaining([{ key: '潮汐值班表', value: '每周二、四' }]),
    body: '码头夜班。\n清晨交接。',
  })
  expect(restored.tagIds).toHaveLength(2)
})

test('双击建卡、拖动和缩放，连接卡片、文字及连线，框选分组、复制粘贴与撤销重做', async ({ page }) => {
  await page.goto('/#/writing')
  await newStoryWork(page, '雾港画布')
  const story = await openStoryWindow(page)
  await newCard(story, '守灯人', { x: 130, y: 125 })
  await newCard(story, '船长', { x: 565, y: 125 })
  await newCard(story, '旅客', { x: 435, y: 335 })
  await connect(story, '守灯人', 'right', await midpoint(storyCard(story, '船长')))
  const panel = cardPanel(story)
  await panel.getByLabel('关系名称', { exact: true }).fill('师徒')
  await panel.getByRole('combobox', { name: '箭头方向' }).selectOption('both')
  await panel.getByRole('combobox', { name: '线条样式' }).selectOption('dash')
  await saveCard(story)
  await expect(story.locator('.story-edge-label')).toHaveText('师徒')
  await closeCard(story)
  const labelEditor = story.locator('.story-inline-label')
  await story.locator('.story-edge-label').dblclick()
  await labelEditor.fill('同行')
  await labelEditor.press('Enter')
  await expect(story.locator('.story-edge-label')).toHaveText('同行')
  const first = (await boardState(story)).scene.edges[0]
  const label = await midpoint(story.locator('.story-edge-label'))
  await connect(story, '旅客', 'top', label)
  await panel.getByLabel('关系名称', { exact: true }).fill('见证')
  await saveCard(story)
  await expect(story.locator('.story-edge-label').filter({ hasText: '见证' })).toBeVisible()
  await closeCard(story)
  const area = await canvas(story).boundingBox()
  await connect(story, '旅客', 'right', { x: area.x + 765, y: area.y + 400 })
  await closeCard(story)
  const connected = (await boardState(story)).scene
  expect(connected.edges[0]).toMatchObject({ direction: 'both', stroke: 'dash', name: '同行' })
  expect(connected.edges[1].to.edgeId).toBe(first.id)
  expect(connected.nodes.find(({ id }) => id === connected.edges[2].to.nodeId)?.kind).toBe('text')

  const keeper = storyCard(story, '守灯人')
  const moved = await midpoint(keeper)
  const startX = connected.nodes[0].x
  const line = story.locator(`[data-edge-id="${first.id}"] .story-line`)
  const beforeLine = Number(await line.getAttribute('x1'))
  await drag(story, moved, { x: moved.x + 25, y: moved.y + 35 })
  await expect.poll(async () => (await boardState(story)).scene.nodes[0].x).toBe(startX + 25)
  await expect(line).toHaveAttribute('x1', String(beforeLine + 25))
  await keeper.click()
  const resize = await midpoint(keeper.locator('.story-resize'))
  await drag(story, resize, { x: resize.x + 35, y: resize.y + 20 })
  await expect.poll(async () => (await boardState(story)).scene.nodes[0].width).toBe(245)

  // Marquee both top cards, create and then move the frame with its contents.
  await drag(story, { x: area.x + 103, y: area.y + 80 }, { x: area.x + 795, y: area.y + 320 })
  await expect(keeper).toHaveAttribute('aria-pressed', 'true')
  await expect(storyCard(story, '船长')).toHaveAttribute('aria-pressed', 'true')
  await action(story, '分组框').click()
  await closeCard(story)
  const frame = story.locator('.story-group-title')
  const beforeGroup = (await boardState(story)).scene.nodes
  const start = await midpoint(frame)
  await drag(story, start, { x: start.x + 42, y: start.y + 18 })
  await expect.poll(async () => (await boardState(story)).scene.nodes[0].x).toBe(beforeGroup[0].x + 42)
  const afterMove = (await boardState(story)).scene.nodes
  expect(afterMove[1].x).toBe(beforeGroup[1].x + 42)
  expect(afterMove[2]).toEqual(beforeGroup[2])
  await action(story, '撤销画布操作').click()
  await expect.poll(async () => (await boardState(story)).scene.nodes).toEqual(beforeGroup)
  await action(story, '重做画布操作').click()
  await expect.poll(async () => (await boardState(story)).scene.nodes).toEqual(afterMove)

  await frame.click()
  const clipboard = await story.evaluate(() => {
    const data = new DataTransfer()
    document.querySelector('.story-canvas').dispatchEvent(new ClipboardEvent('copy', { bubbles: true, cancelable: true, clipboardData: data }))
    return data.getData('text/plain')
  })
  await story.evaluate((text) => {
    const data = new DataTransfer()
    data.setData('text/plain', text)
    document.querySelector('.story-canvas').dispatchEvent(new ClipboardEvent('paste', { bubbles: true, cancelable: true, clipboardData: data }))
  }, clipboard)
  await expect.poll(async () => (await boardState(story)).scene.nodes.filter(({ kind }) => kind === 'group').length).toBe(2)
  await expect(storyCard(story, '守灯人')).toHaveCount(2)
  await action(story, '撤销画布操作').click()
  await expect(storyCard(story, '守灯人')).toHaveCount(1)

  await story.mouse.move(area.x + 500, area.y + 260)
  await story.mouse.wheel(0, -120)
  await expect.poll(async () => (await boardState(story)).view.zoom).toBeGreaterThan(1)
  const zoomed = await boardState(story)
  await drag(story, { x: area.x + 910, y: area.y + 450 }, { x: area.x + 965, y: area.y + 478 }, { button: 'middle' })
  await expect.poll(async () => (await boardState(story)).view.x).toBe(zoomed.view.x + 55)
  const panned = await boardState(story)
  await canvas(story).dispatchEvent('wheel', { deltaX: 24, deltaY: 32, deltaMode: 0 })
  await expect.poll(async () => (await boardState(story)).view.x).toBe(panned.view.x - 24)
  const saved = await boardState(story)
  expect(saved.view.zoom).toBe(panned.view.zoom)
  await story.reload()
  await expect(canvas(story)).toHaveAttribute('data-zoom', String(saved.view.zoom))
  expect(await boardState(story)).toEqual(saved)
})

test('双指缩放以触点为中心并保存视角', async ({ page, context, browserName }) => {
  test.skip(browserName !== 'chromium')
  await page.goto('/#/writing')
  await newStoryWork(page, '触屏画布')
  const story = await openStoryWindow(page)
  const cdp = await context.newCDPSession(story)
  await cdp.send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 2 })
  const area = await canvas(story).boundingBox()
  const point = (x, id) => ({ x: area.x + x, y: area.y + 220, id })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [point(180, 1), point(260, 2)] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [point(135, 1), point(335, 2)] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect.poll(async () => (await boardState(story))?.view.zoom ?? 1).toBeGreaterThan(1.25)
})

test('编辑器双向同步章节与卡片，两个画布标签页的草稿冲突可见', async ({ page, context }) => {
  await page.goto('/#/writing')
  await newStoryWork(page, '带章节的故事')
  const story = await openStoryWindow(page)
  await action(story, '新建卡片').click()
  const panel = cardPanel(story)
  const linked = panel.getByRole('combobox', { name: '关联章节', exact: true })
  await expect(linked.locator('option:checked')).toHaveText('第 1 章 · 第一章')
  await addStoryChapter(page, '出海')
  await expect(chapterHeading(page)).toHaveText('出海')
  await expect(linked.locator('option').filter({ hasText: '第 2 章 · 出海' })).toHaveCount(1)
  await linked.selectOption({ label: '第 2 章 · 出海' })
  await panel.getByText('章节状态', { exact: true }).click()
  await action(panel, '添加状态').click()
  const start = panel.getByRole('combobox', { name: '从章节起' })
  await start.selectOption({ label: '第 2 章 · 出海' })
  await panel.getByLabel('状态', { exact: true }).fill('接任船长')
  await fillNewCard(story, '周行')
  await closeCard(story)
  await expect(storyEntry(page)).toHaveAttribute('title', '本章关联 1 张卡片 · 周行')
  await editCard(story, '周行')
  await moveChapter(page, '出海', 'up')
  await expect(start.locator('option:checked')).toHaveText('第 1 章 · 出海')
  await renameStoryChapter(page, '出海', '远航')
  await expect(start.locator('option:checked')).toHaveText('第 1 章 · 远航')

  const second = await context.newPage()
  await second.goto(story.url())
  await editCard(second, '周行')
  await cardPanel(second).getByLabel('正文', { exact: true }).fill('未保存的草稿')
  await panel.getByLabel('名称', { exact: true }).fill('周船长')
  await saveCard(story)
  await expect(storyEntry(page)).toHaveAttribute('title', '本章关联 1 张卡片 · 周船长')
  await expect(storyCard(second, '周船长')).toBeVisible()
  await saveCard(second)
  await expect(cardPanel(second).getByRole('status')).toContainText('在另一个窗口更新')
  await expect(cardPanel(second).getByLabel('正文', { exact: true })).toHaveValue('未保存的草稿')
  expect((await boardState(second)).scene.nodes[0].body).toBe('')
})
