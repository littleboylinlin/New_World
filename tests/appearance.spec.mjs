import { expect, test } from './app-test.mjs'

const textArea = (page) => page.getByRole('textbox', { name: '章节正文' })
const root = (page) => page.locator('html')

async function newNovel(page, name) {
  await page.goto('/#/original')
  await page.getByRole('button', { name: '新建小说' }).click()
  await page.getByRole('textbox', { name: '作品名' }).fill(name)
  await page.getByRole('button', { name: '创建小说' }).click()
  await expect(textArea(page)).toBeVisible()
}

test('编辑器的「外观」面板可切换主题、字号和英文字体，刷新后仍保留', async ({ page }, testInfo) => {
  await newNovel(page, 'The Lighthouse')
  await textArea(page).fill('The keeper climbed the stairs at dusk. 灯塔守望者在黄昏时爬上台阶。')
  await expect(root(page)).toHaveAttribute('data-theme', 'system')
  await expect(root(page)).toHaveAttribute('data-latin-font', 'times')

  const toggle = page.getByRole('button', { name: '外观', exact: true })
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-expanded', 'true')
  const panel = page.getByRole('group', { name: '外观' })
  await panel.getByRole('radio', { name: '黑色' }).check()
  await expect(root(page)).toHaveAttribute('data-theme', 'dark')
  await expect(root(page)).toHaveCSS('background-color', 'rgb(19, 18, 16)')
  await expect(page.locator('.editor-paper')).toHaveCSS('background-color', 'rgb(26, 24, 22)')
  await expect(page.locator('.site-header')).toHaveCSS('background-color', 'rgb(22, 19, 15)')

  const size = panel.locator('output')
  await expect(size).toHaveText('18 px')
  await panel.getByRole('button', { name: '放大字号' }).click()
  await panel.getByRole('button', { name: '放大字号' }).click()
  await expect(size).toHaveText('20 px')
  await expect(textArea(page)).toHaveCSS('font-size', '20px')
  await panel.getByRole('combobox', { name: '英文字体' }).selectOption('lora')
  await expect(textArea(page)).toHaveCSS('font-family', /^"New World Lora"/)
  await page.screenshot({ path: testInfo.outputPath('editor-appearance-dark.png') })
  await page.keyboard.press('Escape')
  await expect(panel).toBeHidden()
  await expect(toggle).toBeFocused()

  await page.reload()
  await expect(textArea(page)).toBeVisible()
  await expect(root(page)).toHaveAttribute('data-theme', 'dark')
  await expect(root(page)).toHaveAttribute('data-latin-font', 'lora')
  await expect(textArea(page)).toHaveCSS('font-size', '20px')
})

test('字号有上下限，可恢复默认', async ({ page }) => {
  await newNovel(page, '字号')
  await page.getByRole('button', { name: '外观', exact: true }).click()
  const panel = page.getByRole('group', { name: '外观' })
  const smaller = panel.getByRole('button', { name: '缩小字号' })
  for (let step = 0; step < 4; step++) await smaller.click()
  await expect(panel.locator('output')).toHaveText('14 px')
  await expect(smaller).toBeDisabled()
  const larger = panel.getByRole('button', { name: '放大字号' })
  for (let step = 0; step < 14; step++) await larger.click()
  await expect(panel.locator('output')).toHaveText('28 px')
  await expect(larger).toBeDisabled()

  await panel.getByRole('button', { name: '更多设置…' }).click()
  const dialog = page.getByRole('dialog', { name: '设置' })
  const section = dialog.getByRole('region', { name: '外观', exact: true })
  await expect(section.getByRole('heading', { level: 3, name: '外观' })).toBeFocused()
  await section.getByRole('button', { name: '使用默认字号' }).click()
  await expect(section.locator('output')).toHaveText('18 px')
  await expect(section.getByRole('button', { name: '使用默认字号' })).toBeDisabled()
  await expect.poll(() => page.evaluate(() => document.documentElement.style.getPropertyValue('--reading-size'))).toBe('')
})

test('跟随系统时随系统深浅色切换', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/')
  await expect(root(page)).toHaveCSS('background-color', 'rgb(19, 18, 16)')
  await page.emulateMedia({ colorScheme: 'light' })
  await expect(root(page)).toHaveCSS('background-color', 'rgb(244, 238, 226)')
})

test('设置中可分别选择中英文字体，米黄主题不改变导出样式', async ({ page }, testInfo) => {
  await newNovel(page, '雾港')
  await textArea(page).fill('Fog over the harbour. 雾笼罩着港口。')
  await page.getByRole('button', { name: '设置', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '设置' })
  const section = dialog.getByRole('region', { name: '外观', exact: true })
  await section.getByRole('radio', { name: /米黄色/ }).check()
  await section.getByRole('radiogroup', { name: '英文字体' }).getByRole('radio', { name: /Georgia/ }).check()
  await section.getByRole('radiogroup', { name: '中文字体' }).getByRole('radio', { name: /楷体/ }).check()
  await expect(root(page)).toHaveAttribute('data-theme', 'beige')
  await expect(root(page)).toHaveAttribute('data-latin-font', 'georgia')
  await expect(root(page)).toHaveAttribute('data-cjk-font', 'kai')
  await expect(textArea(page)).toHaveCSS('font-family', /^Georgia, Gelasio, "Kaiti SC"/)
  await page.screenshot({ path: testInfo.outputPath('home-settings-appearance.png') })
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()

  await page.getByRole('button', { name: '导出', exact: true }).click()
  const exporting = page.getByRole('dialog', { name: '导出编辑稿' })
  await exporting.getByRole('radio', { name: 'PDF' }).check()
  const paper = exporting.locator('.export-preview-page')
  await expect(paper).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await expect(paper.locator('.export-paper')).toHaveCSS('color', 'rgb(0, 0, 0)')
  await expect(paper.locator('.export-paper')).toHaveCSS('font-family', /^"Times New Roman"/)
})
