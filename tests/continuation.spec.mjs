import { readFile } from 'node:fs/promises'
import { expect, test } from './app-test.mjs'
import { file } from './fixtures.mjs'

const originalList = (page) => page.getByRole('list', { name: '原文列表' })
const draftList = (page) => page.getByRole('list', { name: '续写列表' })
const editor = (page) => page.getByRole('textbox', { name: '章节正文' })

test('按原作进入续写项目，原文与续写分开，移除原文不删除稿件', async ({ page }) => {
  await page.goto('/#/reference')
  const first = file('港湾.txt', '潮水漫过石阶。')
  const other = file('山谷.txt', '山谷里有回声。')
  const extra = file('港湾补篇.txt', '港外有艘小船。')
  await page.locator('input[type=file]').setInputFiles([first, other])
  await expect(page.getByText('已导入 2 部。')).toBeVisible()
  await page.getByRole('link', { name: '查看 港湾', exact: true }).click()
  await expect(page.getByRole('heading', { name: '续写列表' })).toBeVisible()
  await expect(originalList(page).getByRole('link', { name: '查看原文 港湾', exact: true })).toBeVisible()
  await expect(originalList(page)).not.toContainText('山谷')
  await expect(page.getByText('还没有续写。', { exact: false })).toBeVisible()
  const projectUrl = page.url()
  await page.locator('input[type=file]').setInputFiles(extra)
  await expect(originalList(page).getByRole('listitem')).toHaveCount(2)

  await page.getByRole('button', { name: '新建续写' }).click()
  await page.getByRole('textbox', { name: '续写名称' }).fill('小船靠岸之后')
  await page.getByRole('button', { name: '开始续写' }).click()
  await expect(editor(page)).toHaveText('')
  await editor(page).fill('岸边有人点起一盏灯。')
  await page.getByRole('link', { name: '返回续写项目' }).click()
  await expect(draftList(page).getByRole('link', { name: '小船靠岸之后' })).toBeVisible()
  await page.getByRole('link', { name: '查看原文 港湾补篇' }).click()
  await expect(page.getByRole('article')).toHaveText('港外有艘小船。')
  await page.getByRole('button', { name: '以原文为底稿续写' }).click()
  await expect(editor(page)).toHaveText('港外有艘小船。')
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: '下载原文件' }).click()])
  expect(download.suggestedFilename()).toBe(extra.name)
  expect(await readFile(await download.path())).toEqual(extra.buffer)

  await page.goto(projectUrl)
  const row = originalList(page).getByRole('listitem').filter({ has: page.getByRole('link', { name: '查看原文 港湾', exact: true }) })
  await row.getByRole('button', { name: '移除原文' }).click()
  await page.getByRole('button', { name: '确认移除原文' }).click()
  await expect(originalList(page).getByRole('listitem')).toHaveCount(1)
  await expect(draftList(page).getByRole('listitem')).toHaveCount(2)
  await draftList(page).getByRole('link', { name: '小船靠岸之后' }).click()
  await expect(editor(page)).toHaveText('岸边有人点起一盏灯。')
  await page.goto('/#/reference')
  await expect(page.getByRole('link', { name: '查看 港湾', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: '查看 山谷', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: '查看 港湾补篇', exact: true })).toHaveCount(0)
})

test('旧版独立稿件沿用原链接，可添加原文且保留章节', async ({ page }) => {
  await page.goto('/#/reference')
  await expect(page.getByText('还没有参考原作')).toBeVisible()
  const { id, editionId } = await page.evaluate(async () => {
    const db = await new Promise((resolve, reject) => {
      const request = indexedDB.open('new-world-library', 2)
      request.onsuccess = () => resolve(request.result)
      request.onerror = () => reject(request.error)
    })
    const library = 'reference'
    const id = crypto.randomUUID()
    const editionId = crypto.randomUUID()
    const chapterId = crypto.randomUUID()
    const tx = db.transaction(['books', 'editions', 'chapters'], 'readwrite')
    tx.objectStore('books').add({ library, id, title: '旧续写项目', format: 'draft', importedAt: 1 })
    tx.objectStore('editions').add({ library, bookId: id, id: editionId, name: '旧编辑稿', source: 'blank', notes: [], chapters: [{ id: chapterId, title: '第一章' }], createdAt: 1, revision: 0 })
    tx.objectStore('chapters').add({ library, bookId: id, editionId, id: chapterId, content: { type: 'doc', content: [{ type: 'paragraph', content: [{ type: 'text', text: '旧稿里的正文。' }] }] }, revision: 1 })
    await new Promise((resolve, reject) => { tx.oncomplete = resolve; tx.onabort = () => reject(tx.error) })
    db.close()
    return { id, editionId }
  })
  await page.goto(`/#/reference/${id}/${editionId}`)
  await expect(editor(page)).toHaveText('旧稿里的正文。')
  await page.getByRole('link', { name: '返回续写项目' }).click()
  await expect(page.getByText('当前没有原文。', { exact: false })).toBeVisible()
  await expect(draftList(page).getByRole('link', { name: '旧编辑稿' })).toBeVisible()
  await page.locator('input[type=file]').setInputFiles(file('补上的原文.txt', '后来找到的原作。'))
  await expect(originalList(page).getByRole('link', { name: '查看原文 补上的原文' })).toBeVisible()
  await draftList(page).getByRole('link', { name: '旧编辑稿' }).click()
  await expect(editor(page)).toHaveText('旧稿里的正文。')
})
