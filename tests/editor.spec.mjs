test('Markdown 与 HTML 保留样式，导入和粘贴隔离脚本与外部资源', async ({ page, context }) => {
  const requests = []
  await context.route('https://example.invalid/**', (route) => { requests.push(route.request().url()); return route.abort() })
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  const markdown = file('书页.md', '# 起航\n\n**浓雾**与*潮声*。\n\n> 引用正文\n\n- 第一项\n\n---')
  const hostile = '<p style="font-weight:700">安全正文</p><p><u>留下下划线</u></p><img src="https://example.invalid/photo" onerror="window.scriptRan=true"><iframe src="https://example.invalid/frame"></iframe><script>window.scriptRan=true</script>'
  await shelf(page, 'reference')
  await upload(page, [markdown, file('岛屿.html', hostile)])
  await openBook(page, '书页')
  await convert(page)
  for (const [tag, expected] of [['h1', '起航'], ['strong', '浓雾'], ['em', '潮声'], ['blockquote', '引用正文'], ['ul', '第一项']]) {
    await expect(textArea(page).locator(tag)).toContainText(expected)
  }
  await expect(textArea(page).locator('hr')).toHaveCount(1)
  await originalBytes(page, markdown)
  await shelf(page, 'reference')
  await openBook(page, '岛屿')
  await convert(page)
  await expect(textArea(page).locator('strong')).toHaveText('安全正文')
  await expect(textArea(page).locator('u')).toHaveText('留下下划线')
  await page.evaluate(async (markup) => {
    await navigator.clipboard.write([new ClipboardItem({ 'text/html': new Blob([markup], { type: 'text/html' }) })])
  }, '<p><em>粘贴文字</em></p><img src="https://example.invalid/pasted"><script>window.scriptRan=true</script>')
  await textArea(page).click()
  await page.keyboard.press('Control+End')
  await page.keyboard.press('Control+v')
  await expect(textArea(page).locator('em')).toHaveText('粘贴文字')
  expect(await page.evaluate(() => window.scriptRan)).toBeUndefined()
  expect(requests).toEqual([])
})

